namespace Barbican.Core.Settings.Vacation;

/// <summary>The default <see cref="IVacationService"/>: every call runs on the pool (D-M6-00).</summary>
public sealed class VacationService(IAccountManager accounts, IHookBus hooks, TimeProvider time, ICalendarStore? calendars = null, ICalendarWriter? calendarWriter = null) : IVacationService
{
    /// <summary>The JMAP capability of VacationResponse (RFC 8621 section 8).</summary>
    public const string Capability = "urn:ietf:params:jmap:vacationresponse";

    private readonly VacationCalendar? _calendar = calendars is not null && calendarWriter is not null ? new(calendars, calendarWriter, time) : null;

    private const string BlockSetting = "vacationBlockCalendar";

    /// <inheritdoc />
    public event EventHandler<VacationChangedEventArgs>? Changed;

    /// <inheritdoc />
    public Task<Result<VacationSettings>> LoadAsync(string accountKey, CancellationToken ct) => Task.Run(() => LoadCoreAsync(accountKey, true, ct), ct);

    /// <inheritdoc />
    public Task<Result<VacationSettings>> SaveAsync(string accountKey, VacationSettings settings, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(settings);
        return Task.Run(() => SaveCoreAsync(accountKey, settings, ct), ct);
    }

    private static VacationHookPayload View(VacationSettings s) => new(s.Enabled, Boundary(s.From, false), Boundary(s.To, true), s.Subject, s.TextBody, s.HtmlBody);

    // the days are UTC boundaries in VacationResponse and in the script
    private static string? Boundary(DateOnly? day, bool end) => day is { } d ? d.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture) + (end ? "T23:59:59Z" : "T00:00:00Z") : null;

    private static DateOnly? DayOf(string? iso) =>
        iso is not null && DateTimeOffset.TryParse(iso, CultureInfo.InvariantCulture, DateTimeStyles.AssumeUniversal, out var t) ? DateOnly.FromDateTime(t.UtcDateTime) : null;

    private static bool Flag(JsonNode? n, string key) => n is JsonObject o && o[key] is JsonValue v && v.TryGetValue<bool>(out var b) && b;

    private static VacationForward? ForwardOf(JsonNode? n) =>
        n is JsonObject o && o["to"] is JsonValue to && to.TryGetValue<string>(out var address) ? new VacationForward(Flag(o, "enabled"), address, Flag(o, "keepCopy")) : null;

    private static VacationAudience? AudienceOf(JsonNode? n) =>
        n is JsonObject o && FilterRules.Str(o, "only") is { } only && o["domains"] is JsonArray d ? new VacationAudience(only, [.. d.Select(x => x.AsString()).OfType<string>()]) : null;

    private static string? Problem(JsonObject response)
    {
        foreach (var map in new[] { "notUpdated", "notCreated", "notDestroyed" })
        {
            if (response[map] is JsonObject { Count: > 0 } failed)
            {
                var first = failed.First();
                return SetErrors.From(first.Key, first.Value!).Message;
            }
        }

        return null;
    }

    // the metadata of the filters script with the vacation extras the settings ask for; null when it is already what the script says
    private static JsonObject? WithExtras(JsonNode metadata, VacationSettings s, IReadOnlyList<string> extensions)
    {
        var meta = (JsonObject)metadata.DeepClone();
        var wasIncluded = Flag(meta, "includeVacation");
        if (s.Forward is { } f && (f.Enabled || f.To.Trim().Length > 0))
        {
            var forward = new JsonObject { ["enabled"] = f.Enabled, ["to"] = f.To.Trim(), ["keepCopy"] = f.KeepCopy };
            if (Boundary(s.From, false) is { } from)
            {
                forward["activeFrom"] = from;
            }

            if (Boundary(s.To, true) is { } until)
            {
                forward["activeUntil"] = until;
            }

            meta["vacationForward"] = forward;
        }
        else
        {
            meta.Remove("vacationForward");
        }

        if (s.Audience is { } a)
        {
            meta["vacationAudience"] = new JsonObject { ["only"] = a.Only, ["domains"] = new JsonArray([.. a.Domains.Select(d => (JsonNode?)JsonValue.Create(d))]) };
        }
        else
        {
            meta.Remove("vacationAudience");
        }

        if (s.Enabled && (wasIncluded || extensions.Contains("include", StringComparer.Ordinal)))
        {
            meta["includeVacation"] = true;
        }
        else
        {
            meta.Remove("includeVacation");
        }

        return JsonNode.DeepEquals(meta, metadata) ? null : meta;
    }

    #pragma warning disable MA0051 // The load combines the two protocol representations before announcing one view.
    private async Task<Result<VacationSettings>> LoadCoreAsync(string accountKey, bool announce, CancellationToken ct)
    {
        var client = FilterAccess.ClientFor(accounts, accountKey);
        if (!client.IsOk)
        {
            return Result<VacationSettings>.Fail(client.Error!);
        }

        var http = client.Value!;
        var store = new SieveScriptStore(http);
        if (!http.Session.Has(Capability) && !store.Available)
        {
            return Result<VacationSettings>.Fail(new ValidationError("This server has no out-of-office reply."));
        }

        var settings = new VacationSettings(false, string.Empty, string.Empty, null, null, null, null, null, true);
        if (http.Session.Has(Capability))
        {
            var args = new JsonObject { ["accountId"] = http.Session.AccountFor(Capability), ["ids"] = new JsonArray("singleton") };
            var got = await ReaderCalls.CallAsync(http, "VacationResponse/get", args, ct).ConfigureAwait(false);
            if (!got.IsOk)
            {
                return Result<VacationSettings>.Fail(got.Error!);
            }

            var vr = (got.Value!["list"] as JsonArray)?.FirstOrDefault();
            settings = settings with
            {
                Enabled = Flag(vr, "isEnabled"),
                Subject = vr.Str("subject") ?? string.Empty,
                TextBody = vr.Str("textBody") ?? string.Empty,
                HtmlBody = vr.Str("htmlBody"),
                From = DayOf(vr.Str("fromDate")),
                To = DayOf(vr.Str("toDate")),
            };
        }

        // what the filters script holds for the reply: the forward, the audience, and whether it runs from there; a script that cannot be read leaves these out (Bulwark forwardUnknown)
        if (store.Available && (await store.ReadAsync(ct).ConfigureAwait(false)) is { IsOk: true, Value: { } read })
        {
            var meta = SieveScript.Parse(read.Text).Metadata;
            settings = settings with
            {
                Enabled = settings.Enabled || (Flag(meta, "includeVacation") && read.Target?.IsActive == true),
                Forward = ForwardOf(meta["vacationForward"]),
                Audience = AudienceOf(meta["vacationAudience"]),
            };
        }

        if (http.Session.Has(FolderAdminMetadata.Capability) && (await FolderAdminMetadata.ReadAsync(http, ct).ConfigureAwait(false)) is { IsOk: true } stored)
        {
            settings = settings with { BlockCalendar = FolderAdminMetadata.ValueOf(stored.Value.Metadata, BlockSetting) is not JsonValue v || !v.TryGetValue<bool>(out var b) || b };
        }

        if (announce)
        {
            var view = View(settings);
            hooks.Fire(HookNames.OnVacationLoaded, () => view);
            await SyncCalendarAsync(accountKey, http, settings, null, true, ct).ConfigureAwait(false);
        }

        return Result<VacationSettings>.Ok(settings);
    }

    #pragma warning restore MA0051

    private async Task<Result<VacationSettings>> SaveCoreAsync(string accountKey, VacationSettings settings, CancellationToken ct)
    {
        if (VacationRules.Problem(settings) is { } why)
        {
            return Result<VacationSettings>.Fail(new ValidationError(why));
        }

        var client = FilterAccess.ClientFor(accounts, accountKey);
        if (!client.IsOk)
        {
            return Result<VacationSettings>.Fail(client.Error!);
        }

        var http = client.Value!;
        var before = await LoadCoreAsync(accountKey, false, ct).ConfigureAwait(false);
        var view = View(settings);
        if (!await hooks.AllowAsync(HookNames.OnBeforeVacationUpdate, () => view, ct).ConfigureAwait(false))
        {
            return Result<VacationSettings>.Fail(FilterAccess.StoppedByPlugin);
        }

        if (http.Session.Has(Capability))
        {
            var patch = new JsonObject
            {
                ["isEnabled"] = settings.Enabled,
                ["fromDate"] = view.FromDate,
                ["toDate"] = view.ToDate,
                ["subject"] = settings.Subject,
                ["textBody"] = settings.TextBody,
                ["htmlBody"] = string.IsNullOrWhiteSpace(settings.HtmlBody) ? null : settings.HtmlBody,
            };
            var args = new JsonObject { ["accountId"] = http.Session.AccountFor(Capability), ["update"] = new JsonObject { ["singleton"] = patch } };
            var set = await ReaderCalls.CallAsync(http, "VacationResponse/set", args, ct).ConfigureAwait(false);
            if (!set.IsOk)
            {
                return Result<VacationSettings>.Fail(set.Error!);
            }

            if (Problem(set.Value!) is { } refused)
            {
                return Result<VacationSettings>.Fail(new ValidationError(refused));
            }
        }

        // the reply itself is saved even when the filters part is not: say so (Bulwark VacationFiltersError)
        var extras = await SaveExtrasAsync(http, settings, ct).ConfigureAwait(false);
        if (!extras.IsOk)
        {
            return Result<VacationSettings>.Fail(new ValidationError("The auto-reply may have been saved, but forwarding or its recipients could not be confirmed: " + extras.Error!.Message));
        }

        var loaded = await LoadCoreAsync(accountKey, false, ct).ConfigureAwait(false);
        if (before.IsOk && RelevantChanged(before.Value!, settings))
        {
            await SyncCalendarAsync(accountKey, http, settings, before.Value, false, ct).ConfigureAwait(false);
        }
        hooks.Fire(HookNames.OnVacationUpdate, () => view);
        Changed?.Invoke(this, new VacationChangedEventArgs(accountKey));
        return loaded;
    }

    private static bool RelevantChanged(VacationSettings a, VacationSettings b) =>
        a.Enabled != b.Enabled || a.From != b.From || a.To != b.To || a.BlockCalendar != b.BlockCalendar || !string.Equals(a.Subject, b.Subject, StringComparison.Ordinal);

    private async Task SyncCalendarAsync(string accountKey, IJmapClient client, VacationSettings settings, VacationSettings? before, bool load, CancellationToken ct)
    {
        if (_calendar is null) return;
        try { await _calendar.SyncAsync(accountKey, client, settings, before, load, ct).ConfigureAwait(false); }
        catch (Exception ex) when (ex is not OperationCanceledException) { /* The reply is saved independently of calendar sync. */ }
    }

    private async Task<Result<Unit>> SaveExtrasAsync(IJmapClient http, VacationSettings settings, CancellationToken ct)
    {
        var store = new SieveScriptStore(http);
        if (store.Available)
        {
            var read = await store.ReadAsync(ct).ConfigureAwait(false);
            if (!read.IsOk)
            {
                return Result<Unit>.Fail(read.Error!);
            }

            var current = read.Value!;
            var parsed = SieveScript.Parse(current.Text);
            if (WithExtras(parsed.Metadata, settings, current.Extensions) is { } meta)
            {
                if (parsed.Locked)
                {
                    return Result<Unit>.Fail(new ValidationError("The filter script was edited by hand, so forwarding and recipients cannot be stored in it."));
                }

                var saved = await store.SaveAsync(SieveScript.GenerateMeta(meta, parsed.External, current.Extensions), current, ct).ConfigureAwait(false);
                if (!saved.IsOk)
                {
                    return saved;
                }
            }
        }

        if (!http.Session.Has(FolderAdminMetadata.Capability))
        {
            return Result<Unit>.Ok(default);
        }

        return await FolderAdminMetadata.UpdateAsync(http, meta =>
            FolderAdminMetadata.ValueOf(meta, BlockSetting) is JsonValue v && v.TryGetValue<bool>(out var was) && was == settings.BlockCalendar || (FolderAdminMetadata.ValueOf(meta, BlockSetting) is null && settings.BlockCalendar)
                ? null
                : new JsonObject { ["metadata/" + FolderAdminMetadata.ValueKey(BlockSetting)] = FolderAdminMetadata.Entry(BlockSetting, settings.BlockCalendar, time.GetUtcNow()) }, ct).ConfigureAwait(false);
    }
}
