#!/usr/bin/env python3
"""Generate src/plugin_catalog.rs from spec/plugins/{hooks,slots,host-api}.csv.

  python tools/gen-plugin-catalog.py          write the file
  python tools/gen-plugin-catalog.py --check  exit 1 if the committed file is stale

The committed CSVs are the source of truth (tools/extract-plugin-catalogue.py refreshes hooks.csv and slots.csv
from a Bulwark checkout). The generated file holds const tables for hooks (name, group, kind, permission, budget_ms,
fail_closed), slots (name, area, kind, permissions) and host-API method names, plus the alias table that maps
Barbican's own native-plugin hook names to Bulwark's. The Rust tests in src/plugin_catalog_check.rs compares the tables with
the CSVs, so a stale file fails `cargo test` as well.
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "plugins"
OUT = ROOT / "src" / "plugin_catalog.rs"

# Barbican's old native hook names -> the Bulwark hook they stand for: (old, new, why). Checked against the CSV.
ALIASES = [
    ("email.details", "onEmailOpen",
     "fires when a message is opened (email:read); the rows a plugin returns are drawn where Bulwark's "
     "`email-details-section` slot sits (a section in the message details)"),
    ("compose.check", "onBeforeEmailSend",
     "Bulwark's send intercept: a handler that fails or times out stops the send"),
]


def rows(name):
    with (SPEC / name).open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def lit(s):
    assert s.isascii() and '"' not in s and "\\" not in s and "\n" not in s, s
    return f'"{s}"'


def render():
    hooks, slots, api = rows("hooks.csv"), rows("slots.csv"), rows("host-api.csv")
    names = {h["name"] for h in hooks}
    for old, new, _ in ALIASES:
        assert new in names, f"alias target {new} is not a catalogued hook"
        assert old not in names, f"alias {old} collides with a catalogued hook"
    cap = lambda s: s[0].upper() + s[1:]
    o = [
        "// <auto-generated>",
        "// Generated by tools/gen-plugin-catalog.py from spec/plugins/{hooks,slots,host-api}.csv (Bulwark 1.21.2).",
        "// Do not edit; run `python tools/gen-plugin-catalog.py`. `plugin_catalog_check` (cargo test) compares it with the CSVs.",
        "// </auto-generated>",
        "#![allow(dead_code)]",
        "",
        "/// How Bulwark treats a hook's handlers.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub enum HookKind { Observer, Intercept, Transform, Takeover }",
        "",
        "/// One catalogued hook (spec/plugins/hooks.csv). `permission` is the plugin permission a handler needs.",
        "#[derive(Clone, Copy, Debug)]",
        "pub struct Hook {",
        "    pub name: &'static str,",
        "    pub group: &'static str,",
        "    pub kind: HookKind,",
        "    pub permission: &'static str,",
        "    pub budget_ms: u32,",
        "    pub fail_closed: bool,",
        "}",
        "",
        "/// Where a slot is drawn.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub enum SlotKind { Frame, Action, Data }",
        "",
        "/// One catalogued slot (spec/plugins/slots.csv). `permissions` are the plugin permissions a slot needs, joined by `;`.",
        "#[derive(Clone, Copy, Debug)]",
        "pub struct Slot {",
        "    pub name: &'static str,",
        "    pub area: &'static str,",
        "    pub kind: SlotKind,",
        "    pub permissions: &'static str,",
        "}",
        "",
        f"pub const HOOKS: [Hook; {len(hooks)}] = [",
    ]
    for h in hooks:
        assert h["kind"] in ("observer", "intercept", "transform", "takeover"), h
        assert h["fail_closed"] in ("true", "false"), h
        o.append(f'    Hook {{ name: {lit(h["name"])}, group: {lit(h["group"])}, kind: HookKind::{cap(h["kind"])}, '
                 f'permission: {lit(h["permission"])}, budget_ms: {int(h["budget_ms"])}, fail_closed: {h["fail_closed"]} }},')
    o += ["];", "", f"pub const SLOTS: [Slot; {len(slots)}] = ["]
    for s in slots:
        assert s["kind"] in ("frame", "action", "data"), s
        o.append(f'    Slot {{ name: {lit(s["name"])}, area: {lit(s["area"])}, kind: SlotKind::{cap(s["kind"])}, '
                 f'permissions: {lit(s["permissions"])} }},')
    o += ["];", "", "/// Every `api.*` host method name, in catalogue order (spec/plugins/host-api.csv).",
          f"pub const HOST_API: [&str; {len(api)}] = ["]
    for a in api:
        o.append(f'    {lit(a["method"])},')
    o += ["];", "",
          "/// Barbican's own native-plugin hook names and the Bulwark hook each stands for.",
          "pub const HOOK_ALIASES: [(&str, &str); %d] = [" % len(ALIASES)]
    for old, new, why in ALIASES:
        o.append(f"    // {why}")
        o.append(f"    ({lit(old)}, {lit(new)}),")
    o += ["];", "",
          "/// The catalogued hook for a Bulwark name or one of our old aliases.",
          "pub fn lookup_hook(name: &str) -> Option<&'static Hook> {",
          "    let name = resolve_alias(name);",
          "    HOOKS.iter().find(|h| h.name == name)",
          "}",
          "",
          "/// Bulwark's name for one of our old hook names; other names come back unchanged.",
          "pub fn resolve_alias(name: &str) -> &str {",
          "    HOOK_ALIASES.iter().find(|(old, _)| *old == name).map_or(name, |(_, new)| *new)",
          "}",
          ""]
    return "\n".join(o)


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} is stale: run python tools/gen-plugin-catalog.py")
            sys.exit(1)
        print(f"{OUT.name} is up to date")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
