#!/usr/bin/env python3
"""Generate src/Barbican.Core/Plugins/Hooks/HookNames.g.cs from spec/plugins/hooks.csv.

  python tools/gen-hooks.py          write the file
  python tools/gen-hooks.py --check  exit 1 if the committed file is stale

One constant per hook (`HookNames.OnEmailOpen == "onEmailOpen"`), plus `All` and `Milestone1` lists.
Also writes HookPolicies.g.cs: the per-hook budget and fail-closed flag (R2-10; columns budget_ms and
fail_closed, Bulwark lib/plugin-hooks.ts:62-66, :186-188, :290-325).
The files are generated; never edit them by hand (HookNamesTests and HookPolicyTests compare them with the CSV).
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV = ROOT / "spec" / "plugins" / "hooks.csv"
OUT = ROOT / "src" / "Barbican.Core" / "Plugins" / "Hooks" / "HookNames.g.cs"
POLICIES = ROOT / "src" / "Barbican.Core" / "Plugins" / "Hooks" / "HookPolicies.g.cs"


def render():
    with CSV.open(encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    lines = [
        "// <auto-generated>",
        "// Generated by tools/gen-hooks.py from spec/plugins/hooks.csv (Bulwark lib/plugin-hook-catalog.ts).",
        "// Do not edit; run `python tools/gen-hooks.py`.",
        "// </auto-generated>",
        "",
        "namespace Barbican.Core.Plugins.Hooks;",
        "",
        "/// <summary>The names of the plugin hooks (spec/plugins/hooks.csv), as Bulwark spells them.</summary>",
        "public static class HookNames",
        "{",
    ]
    for r in rows:
        name = r["name"]
        const = name[0].upper() + name[1:]
        lines.append(f"    /// <summary>{r['group']}, {r['kind']}: {xml(r['when'])}</summary>")
        lines.append(f'    public const string {const} = "{name}";')
        lines.append("")
    lines.append("    /// <summary>Every hook name, in catalogue order.</summary>")
    lines.append("    public static IReadOnlyList<string> All { get; } =")
    lines.append("    [")
    for r in rows:
        lines.append(f"        {r['name'][0].upper() + r['name'][1:]},")
    lines.append("    ];")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_policies():
    with CSV.open(encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    lines = [
        "// <auto-generated>",
        "// Generated by tools/gen-hooks.py from spec/plugins/hooks.csv (columns budget_ms, fail_closed; R2-10, Bulwark lib/plugin-hooks.ts:62-66, :186-188).",
        "// Do not edit; run `python tools/gen-hooks.py`.",
        "// </auto-generated>",
        "",
        "namespace Barbican.Core.Plugins.Hooks;",
        "",
        "/// <summary>The budget and fail-closed flag of every catalogued hook (spec/plugins/hooks.csv).</summary>",
        "public static partial class HookPolicies",
        "{",
        "    private static readonly Dictionary<string, HookPolicy> Table = new(StringComparer.Ordinal)",
        "    {",
    ]
    for r in rows:
        const = r["name"][0].upper() + r["name"][1:]
        budget = int(r["budget_ms"])
        closed = "true" if r["fail_closed"].strip().lower() == "true" else "false"
        lines.append(f"        [HookNames.{const}] = new(TimeSpan.FromMilliseconds({budget}), {closed}),")
    lines.append("    };")
    lines.append("}")
    return "\n".join(lines) + "\n"


def xml(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\n", " ")


def main():
    outputs = [(OUT, render()), (POLICIES, render_policies())]
    if "--check" in sys.argv:
        stale = [p.name for p, text in outputs if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            print(f"{', '.join(stale)} stale: run python tools/gen-hooks.py")
            sys.exit(1)
        print("HookNames.g.cs and HookPolicies.g.cs are up to date")
        return
    for path, text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
